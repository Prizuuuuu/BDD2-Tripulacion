-- =====================================================================
-- 02. Esquema distribuido (esquema public del coordinador)
-- =====================================================================
-- El staging de la Unidad 1 queda intacto en el esquema staging.
-- Cambios respecto al modelo centralizado:
--   * Las tablas transaccionales llevan id_region (columna de distribución).
--     En tripulante, certificacion, licencia_medica, jornada_laboral y
--     asignacion_horas es la región del hub base del tripulante; en vuelo y
--     asignacion_operacion es la región del aeropuerto de origen del vuelo.
--   * Las PK y UNIQUE incluyen id_region (Citus solo garantiza unicidad
--     dentro de cada shard).
--   * tripulante se fragmenta verticalmente: tripulante (datos operativos,
--     distribuida) y tripulante_personal (datos personales, local en el coordinador).
--   * asignacion_tripulacion se fragmenta verticalmente: asignacion_operacion
--     (manifiesto del vuelo, región del vuelo) y asignacion_horas (horas del
--     tripulante, región de su base).
--   * Las claves foráneas se agregan en 04, después de distribuir.
--   * El trigger fn_validar_asignacion no se migra; sus reglas pasan al
--     procedimiento asignar_tripulante (06_transaccion_2pc.sql).

SET client_min_messages = warning;

DROP TABLE IF EXISTS asignacion_horas, asignacion_operacion, jornada_laboral, licencia_medica,
                     certificacion, vuelo, tripulante_personal, tripulante, hub, aeropuerto, region CASCADE;


-- ---------------------------------------------------------------------
-- TABLAS COMUNES (se replican en todos los nodos)
-- ---------------------------------------------------------------------
CREATE TABLE region (
    id_region      SMALLINT     PRIMARY KEY,
    nombre_region  VARCHAR(10)  NOT NULL UNIQUE
        CHECK (nombre_region IN ('ESTE', 'CENTRAL', 'OESTE'))
);

CREATE TABLE aeropuerto (
    id_aeropuerto  INTEGER      PRIMARY KEY,
    id_region      SMALLINT     NOT NULL,
    codigo_iata    CHAR(3)      NOT NULL UNIQUE
        CHECK (codigo_iata IN (
            'CLT','PHL','JFK','LGA','DCA','MIA','BOS','EWR','BWI','IAD','PIT','RDU','ATL','MCO',
            'DFW','ORD','MSP','DTW','CLE','STL','MCI','MSY','IAH','AUS','SAT','MEM','BNA','MDW',
            'PHX','LAX','SFO','SAN','LAS','SEA','PDX','SLC','DEN','ABQ','TUS','SJC','SNA','OAK')),
    nombre         VARCHAR(100) NOT NULL,
    ciudad         VARCHAR(60)  NOT NULL,
    estado         CHAR(2)      NOT NULL
);

CREATE TABLE hub (
    id_hub                  SMALLINT  PRIMARY KEY,
    id_aeropuerto           INTEGER   NOT NULL UNIQUE,
    fecha_inicio_operacion  DATE      NOT NULL
);


-- ---------------------------------------------------------------------
-- TRIPULANTE (fragmentación vertical)
-- ---------------------------------------------------------------------
-- Fragmento operativo: lo consulta cada región para programar tripulaciones.
CREATE TABLE tripulante (
    id_tripulante    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_region        SMALLINT     NOT NULL,
    id_hub_base      SMALLINT     NOT NULL,
    numero_empleado  CHAR(8)      NOT NULL,
    cargo            VARCHAR(20)  NOT NULL
        CHECK (cargo IN ('PILOTO', 'COPILOTO', 'JEFE_CABINA', 'AUXILIAR_VUELO')),
    estado           VARCHAR(20)  NOT NULL DEFAULT 'ACTIVO'
        CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    PRIMARY KEY (id_tripulante, id_region),
    UNIQUE (numero_empleado, id_region)
);

-- Fragmento personal: lo administra Recursos Humanos de forma centralizada.
CREATE TABLE tripulante_personal (
    id_tripulante     BIGINT       PRIMARY KEY,
    fecha_nacimiento  DATE         NOT NULL,
    fecha_ingreso     DATE         NOT NULL,
    nombre            VARCHAR(50)  NOT NULL,
    apellido          VARCHAR(50)  NOT NULL,
    CHECK (fecha_ingreso >= fecha_nacimiento + INTERVAL '18 years')
);


-- ---------------------------------------------------------------------
-- TABLAS DERIVADAS DEL TRIPULANTE (región de su hub base)
-- ---------------------------------------------------------------------
CREATE TABLE certificacion (
    id_certificacion    BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_region           SMALLINT     NOT NULL,
    id_tripulante       BIGINT       NOT NULL,
    fecha_emision       DATE         NOT NULL,
    fecha_vencimiento   DATE         NOT NULL,
    numero_certificado  CHAR(10)     NOT NULL,
    tipo_certificacion  VARCHAR(30)  NOT NULL
        CHECK (tipo_certificacion IN ('LICENCIA_ATP', 'HABILITACION_TIPO', 'CRM',
                                      'SEGURIDAD_CABINA', 'PRIMEROS_AUXILIOS', 'MERCANCIAS_PELIGROSAS')),
    estado              VARCHAR(20)  NOT NULL
        CHECK (estado IN ('VIGENTE', 'VENCIDA', 'SUSPENDIDA')),
    CHECK (fecha_vencimiento > fecha_emision),
    PRIMARY KEY (id_certificacion, id_region),
    UNIQUE (numero_certificado, id_region)
);

CREATE TABLE licencia_medica (
    id_licencia        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_region          SMALLINT     NOT NULL,
    id_tripulante      BIGINT       NOT NULL,
    fecha_emision      DATE         NOT NULL,
    fecha_vencimiento  DATE         NOT NULL,
    numero_licencia    CHAR(10)     NOT NULL,
    clase_medica       CHAR(1)      NOT NULL
        CHECK (clase_medica IN ('1', '2')),
    restricciones      VARCHAR(60)  NOT NULL DEFAULT 'NINGUNA',
    estado             VARCHAR(20)  NOT NULL
        CHECK (estado IN ('VIGENTE', 'VENCIDA', 'SUSPENDIDA')),
    CHECK (fecha_vencimiento > fecha_emision),
    PRIMARY KEY (id_licencia, id_region),
    UNIQUE (numero_licencia, id_region)
);

CREATE TABLE jornada_laboral (
    id_jornada      BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    id_region       SMALLINT      NOT NULL,
    id_tripulante   BIGINT        NOT NULL,
    hora_inicio     TIMESTAMP     NOT NULL,
    hora_fin        TIMESTAMP     NOT NULL,
    fecha_jornada   DATE          NOT NULL,
    horas_servicio  NUMERIC(4,2)  GENERATED ALWAYS AS
                        (ROUND(EXTRACT(EPOCH FROM (hora_fin - hora_inicio)) / 3600, 2)) STORED,
    tipo_jornada    VARCHAR(20)   NOT NULL
        CHECK (tipo_jornada IN ('VUELO', 'RESERVA', 'ENTRENAMIENTO')),
    CHECK (hora_fin > hora_inicio),
    CHECK (hora_fin - hora_inicio <= INTERVAL '14 hours'),
    CHECK (fecha_jornada = hora_inicio::date),
    PRIMARY KEY (id_jornada, id_region),
    UNIQUE (id_tripulante, fecha_jornada, id_region)
);


-- ---------------------------------------------------------------------
-- VUELO (región del aeropuerto de origen)
-- ---------------------------------------------------------------------
CREATE TABLE vuelo (
    id_vuelo               BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_region              SMALLINT     NOT NULL,
    fecha_salida_real      TIMESTAMP    NOT NULL,
    fecha_llegada_real     TIMESTAMP    NOT NULL,
    id_aeropuerto_origen   INTEGER      NOT NULL,
    id_aeropuerto_destino  INTEGER      NOT NULL,
    retraso_minutos        INTEGER      NOT NULL DEFAULT 0 CHECK (retraso_minutos >= 0),
    numero_vuelo           CHAR(6)      NOT NULL,
    estado                 VARCHAR(20)  NOT NULL
        CHECK (estado IN ('COMPLETADO', 'DESVIADO')),
    CHECK (fecha_llegada_real > fecha_salida_real),
    CHECK (id_aeropuerto_origen <> id_aeropuerto_destino),
    PRIMARY KEY (id_vuelo, id_region)
);


-- ---------------------------------------------------------------------
-- ASIGNACIÓN (fragmentación vertical + horizontal derivada)
-- ---------------------------------------------------------------------
-- Manifiesto del vuelo: lo maneja la región desde donde opera el vuelo.
CREATE TABLE asignacion_operacion (
    id_asignacion     BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    id_region         SMALLINT     NOT NULL,
    id_vuelo          BIGINT       NOT NULL,
    fecha_asignacion  DATE         NOT NULL,
    rol               VARCHAR(20)  NOT NULL
        CHECK (rol IN ('PILOTO', 'COPILOTO', 'JEFE_CABINA', 'AUXILIAR_VUELO')),
    PRIMARY KEY (id_asignacion, id_region)
);

-- Horas del tripulante: las lleva la región de su base (límites de horas, nómina).
CREATE TABLE asignacion_horas (
    id_asignacion  BIGINT        NOT NULL,
    id_region      SMALLINT      NOT NULL,
    id_tripulante  BIGINT        NOT NULL,
    horas_vuelo    NUMERIC(5,2)  NOT NULL CHECK (horas_vuelo > 0),
    PRIMARY KEY (id_asignacion, id_region)
);
